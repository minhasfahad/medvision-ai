"use client";

import { useEffect, useState } from "react";
import Link from "next/link";
import api from "@/src/lib/axios";
import { useAuthStore } from "@/src/lib/store/useAuthStore";
import ProtectedRoute from "@/src/components/ProtectedRoute";
import Reveal from "@/src/components/Reveal";
import SpotlightCard from "@/src/components/SpotlightCard";
import CountUp from "@/src/components/CountUp";
import {
  Brain,
  Clock,
  CheckCircle2,
  AlertTriangle,
  Loader2,
  ClipboardList,
  Activity,
  Sparkles,
  ArrowUpRight,
  Eye,
  User,
} from "lucide-react";

interface RadiologistMetrics {
  totalScans: number;
  pendingReviews: number;
  confirmedScans: number;
  needsRecheck: number;
  reviewedScans: number;
}

export default function RadiologistOverview() {
  const { user } = useAuthStore();
  const [metrics, setMetrics] = useState<RadiologistMetrics | null>(null);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    const fetchRadiologistMetrics = async () => {
      try {
        const res = await api.get("/api/radiologist/metrics");

        if (res.data.success) {
          setMetrics(res.data.metrics);
        }
      } catch (error) {
        console.error("Failed to load radiologist statistics:", error);
      } finally {
        setLoading(false);
      }
    };

    fetchRadiologistMetrics();
  }, []);

  if (loading) {
    return (
      <div className="flex h-64 items-center justify-center text-white gap-3">
        <Loader2 className="w-5 h-5 text-blue-400 animate-spin" />
        <span className="text-lg font-medium animate-pulse">
          Loading radiology overview...
        </span>
      </div>
    );
  }

  const workflowSteps = [
    { icon: Clock, label: "Pending Review", color: "text-amber-400", bg: "bg-amber-500/10 border-amber-500/20" },
    { icon: Eye, label: "Manual Verification", color: "text-blue-400", bg: "bg-blue-500/10 border-blue-500/20" },
    { icon: CheckCircle2, label: "Confirmed / Recheck", color: "text-purple-400", bg: "bg-purple-500/10 border-purple-500/20" },
    { icon: User, label: "Visible to Patient", color: "text-emerald-400", bg: "bg-emerald-500/10 border-emerald-500/20" },
  ];

  return (
    <ProtectedRoute>
      <div className="p-4 sm:p-6 lg:p-8 max-w-[1600px] mx-auto">
        {/* Header */}
        <Reveal>
          <div className="mb-8">
            <span className="inline-flex items-center gap-2 text-xs font-semibold uppercase tracking-[0.2em] text-blue-400/80 mb-3">
              <Sparkles className="w-3.5 h-3.5" />
              Radiology Command Center
            </span>

            <h1 className="text-3xl sm:text-4xl font-bold text-white tracking-wide">
              Welcome,{" "}
              <span className="bg-clip-text text-transparent bg-gradient-to-r from-blue-400 via-purple-400 to-blue-400 animate-gradient-x">
                {user?.name || "Radiology Reviewer"}
              </span>
            </h1>

            <p className="text-gray-400 mt-3 text-sm max-w-2xl leading-6">
              Review AI-generated MRI scan results, verify model predictions, and
              add professional radiology notes for patients.
            </p>
          </div>
        </Reveal>

        {/* Asymmetric bento metric grid */}
        <div className="grid grid-cols-1 md:grid-cols-6 md:auto-rows-[minmax(0,auto)] gap-5 mb-8">
          {/* Hero tile: Total AI Scans */}
          <Reveal variant="zoom" className="md:col-span-3 md:row-span-2" fill>
            <SpotlightCard
              color="96,165,250"
              className="h-full rounded-3xl border border-white/10 bg-white/5 backdrop-blur-sm shadow-xl hover:border-blue-500/40 transition-colors duration-300"
            >
              <div className="h-full flex flex-col justify-between p-7 relative">
                <Brain className="pointer-events-none absolute -right-4 -bottom-4 w-40 h-40 text-blue-500/5" />

                <div className="flex items-center justify-between relative z-10">
                  <span className="text-sm font-semibold text-gray-400 uppercase tracking-wider">
                    Total AI Scans
                  </span>
                  <div className="w-10 h-10 rounded-xl bg-blue-500/10 border border-blue-500/20 flex items-center justify-center">
                    <Brain className="w-5 h-5 text-blue-400" />
                  </div>
                </div>

                <div className="relative z-10">
                  <CountUp
                    value={metrics?.totalScans ?? 0}
                    className="text-6xl sm:text-7xl font-extrabold text-white tracking-tight"
                  />
                  <p className="text-sm text-blue-400 mt-3">
                    MRI results generated by AI across the platform
                  </p>
                </div>
              </div>
            </SpotlightCard>
          </Reveal>

          {/* Pending Reviews */}
          <Reveal delay={80} className="md:col-span-3" fill>
            <SpotlightCard
              color="251,191,36"
              className="h-full rounded-2xl border border-white/10 border-l-4 border-l-amber-500 bg-white/5 backdrop-blur-sm shadow-xl hover:border-amber-500/40 transition-colors duration-300"
            >
              <div className="p-6 flex items-center justify-between h-full">
                <div>
                  <span className="text-sm font-semibold text-gray-400 uppercase tracking-wider">
                    Pending Reviews
                  </span>
                  <CountUp
                    value={metrics?.pendingReviews ?? 0}
                    className="block mt-3 text-4xl font-extrabold text-white"
                  />
                  <p className="text-xs text-amber-400 mt-2">
                    Waiting for radiologist verification
                  </p>
                </div>
                <div className="w-11 h-11 rounded-xl bg-amber-500/10 border border-amber-500/20 flex items-center justify-center flex-none">
                  <Clock className="w-5 h-5 text-amber-400" />
                </div>
              </div>
            </SpotlightCard>
          </Reveal>

          {/* Confirmed Scans */}
          <Reveal delay={140} className="md:col-span-2" fill>
            <SpotlightCard
              color="52,211,153"
              className="h-full rounded-2xl border border-white/10 bg-white/5 backdrop-blur-sm shadow-xl hover:border-emerald-500/40 transition-colors duration-300"
            >
              <div className="p-6 h-full flex flex-col justify-between">
                <div className="flex items-center justify-between">
                  <span className="text-xs font-semibold text-gray-400 uppercase tracking-wider">
                    Confirmed
                  </span>
                  <div className="w-9 h-9 rounded-xl bg-emerald-500/10 border border-emerald-500/20 flex items-center justify-center">
                    <CheckCircle2 className="w-4 h-4 text-emerald-400" />
                  </div>
                </div>
                <div>
                  <CountUp
                    value={metrics?.confirmedScans ?? 0}
                    className="text-3xl font-extrabold text-white"
                  />
                  <p className="text-xs text-emerald-400 mt-2">
                    Predictions verified as correct
                  </p>
                </div>
              </div>
            </SpotlightCard>
          </Reveal>

          {/* Reviewed Scans */}
          <Reveal delay={200} className="md:col-span-2" fill>
            <SpotlightCard
              color="168,85,247"
              className="h-full rounded-2xl border border-white/10 bg-white/5 backdrop-blur-sm shadow-xl hover:border-purple-500/40 transition-colors duration-300"
            >
              <div className="p-6 h-full flex flex-col justify-between">
                <div className="flex items-center justify-between">
                  <span className="text-xs font-semibold text-gray-400 uppercase tracking-wider">
                    Reviewed
                  </span>
                  <div className="w-9 h-9 rounded-xl bg-purple-500/10 border border-purple-500/20 flex items-center justify-center">
                    <ClipboardList className="w-4 h-4 text-purple-400" />
                  </div>
                </div>
                <div>
                  <CountUp
                    value={metrics?.reviewedScans ?? 0}
                    className="text-3xl font-extrabold text-white"
                  />
                  <p className="text-xs text-purple-400 mt-2">
                    Total cases closed out by the team
                  </p>
                </div>
              </div>
            </SpotlightCard>
          </Reveal>

          {/* Needs Recheck — urgent highlight tile */}
          <Reveal delay={260} className="md:col-span-2" fill>
            <Link href="/radiologist-dashboard/needs-recheck" className="block h-full group">
              <div className="relative h-full rounded-2xl border border-red-500/30 bg-red-500/[0.07] backdrop-blur-sm shadow-xl overflow-hidden hover:border-red-500/60 hover:-translate-y-0.5 transition-all duration-300">
                <div className="absolute inset-0 bg-red-600/10 animate-pulse" />
                <div className="relative p-6 h-full flex flex-col justify-between">
                  <div className="flex items-center justify-between">
                    <span className="text-xs font-semibold text-red-300 uppercase tracking-wider">
                      Needs Recheck
                    </span>
                    <div className="w-9 h-9 rounded-xl bg-red-500/15 border border-red-500/30 flex items-center justify-center">
                      <AlertTriangle className="w-4 h-4 text-red-400" />
                    </div>
                  </div>
                  <div>
                    <CountUp
                      value={metrics?.needsRecheck ?? 0}
                      className="text-3xl font-extrabold text-white"
                    />
                    <p className="text-xs text-red-300 mt-2 flex items-center gap-1">
                      Flagged for priority attention
                      <ArrowUpRight className="w-3.5 h-3.5 group-hover:translate-x-0.5 group-hover:-translate-y-0.5 transition-transform" />
                    </p>
                  </div>
                </div>
              </div>
            </Link>
          </Reveal>
        </div>

        {/* Professional Workflow Section */}
        <Reveal delay={320}>
          <div className="relative rounded-2xl border border-white/10 bg-[#12172a]/85 backdrop-blur-sm shadow-xl p-6 sm:p-8 overflow-hidden">
            <div className="relative z-10">
              <div className="flex items-center gap-3 mb-4">
                <div className="w-9 h-9 rounded-xl bg-purple-600/20 border border-purple-500/30 flex items-center justify-center flex-none">
                  <Activity className="w-4 h-4 text-purple-400" />
                </div>
                <h2 className="text-xl font-bold text-white">
                  Radiology Review Workflow
                </h2>
              </div>

              <p className="text-gray-400 text-sm leading-6 max-w-4xl">
                Each AI-generated MRI result is first marked as pending review. The
                radiologist can review the original MRI image, AI segmentation
                output, predicted tumor class, and confidence score. After manual
                verification, the scan can be marked as confirmed, needs recheck,
                incorrect prediction, or unclear image quality. The final
                professional note will be visible to the same patient who uploaded
                the scan.
              </p>

              <div className="mt-6 grid grid-cols-1 sm:grid-cols-2 xl:grid-cols-4 gap-3">
                {workflowSteps.map((step, idx) => {
                  const StepIcon = step.icon;
                  return (
                    <div
                      key={step.label}
                      className={`flex items-center gap-3 rounded-xl border ${step.bg} px-4 py-3`}
                    >
                      <span className="text-xs font-bold text-gray-500">
                        {idx + 1}
                      </span>
                      <StepIcon className={`w-4 h-4 flex-none ${step.color}`} />
                      <span className="text-xs font-semibold text-gray-200">
                        {step.label}
                      </span>
                    </div>
                  );
                })}
              </div>
            </div>
          </div>
        </Reveal>
      </div>
    </ProtectedRoute>
  );
}
